/** Full v3 decode across both capability words. The container reports two
 *  u32 pairs; the honest decoder walks both. */
export interface CapabilityDecode {
  effective: string[];
  sysAdmin: boolean;
}

export function decodeCapabilitiesV3(words: readonly [number, number, number, number, number, number]): CapabilityDecode {
  const effLo = words[0] ?? 0;
  const effHi = words[1] ?? 0;
  const names: string[] = [];
  for (let bit = 0; bit < CAPABILITY_NAMES.length; bit++) {
    const word = bit < 32 ? effLo : effHi;
    const name = CAPABILITY_NAMES[bit];
    if (name !== undefined && (word & (1 << (bit % 32))) !== 0) names.push(name);
  }
  return { effective: names, sysAdmin: (effLo & (1 << 21)) !== 0 };
}

