/** struct fuse_attr — 88 bytes. */
export const FUSE_ATTR_SIZE = 88;

export interface FuseAttrInput {
  ino: number;
  size: number;
  mode: number;
  nlink: number;
}

/** Layout: ino u64, size u64, blocks u64, atime u64, mtime u64, ctime u64,
 *  then ten u32s (three nsecs, mode, nlink, uid, gid, rdev, blksize, flags). */
export function packFuseAttr(input: FuseAttrInput, into: Buffer, offset: number): void {
  const blocks = Math.ceil(input.size / 512);
  into.writeBigUInt64LE(BigInt(input.ino), offset);
  into.writeBigUInt64LE(BigInt(input.size), offset + 8);
  into.writeBigUInt64LE(BigInt(blocks), offset + 16);
  into.writeBigUInt64LE(1700000000n, offset + 24);
  into.writeBigUInt64LE(1700000000n, offset + 32);
  into.writeBigUInt64LE(1700000000n, offset + 40);
  into.writeUInt32LE(0, offset + 48);
  into.writeUInt32LE(0, offset + 52);
  into.writeUInt32LE(0, offset + 56);
  into.writeUInt32LE(input.mode, offset + 60);
  into.writeUInt32LE(input.nlink, offset + 64);
  into.writeUInt32LE(0, offset + 68);
  into.writeUInt32LE(0, offset + 72);
  into.writeUInt32LE(0, offset + 76);
  into.writeUInt32LE(4096, offset + 80);
  into.writeUInt32LE(0, offset + 84);
}

/** struct fuse_entry_out: nodeid u64, generation u64, entry_valid u64,
 *  attr_valid u64, two validity nsecs u32, then attr(88). */
export const ENTRY_OUT_SIZE = 128;

export function packEntryOut(nodeid: number, attr: FuseAttrInput): Buffer {
  const buf = Buffer.alloc(ENTRY_OUT_SIZE);
  buf.writeBigUInt64LE(BigInt(nodeid), 0);
  buf.writeBigUInt64LE(0n, 8);
  // Zero validity windows keep every lookup observable.
  buf.writeBigUInt64LE(0n, 16);
  buf.writeBigUInt64LE(0n, 24);
  buf.writeUInt32LE(0, 32);
  buf.writeUInt32LE(0, 36);
  packFuseAttr(attr, buf, 40);
  return buf;
}

/** struct fuse_attr_out: attr_valid u64, attr_valid_nsec u32, dummy u32,
 *  attr(88). */
export const GETATTR_OUT_SIZE = 104;

export function packGetattrOut(attr: FuseAttrInput): Buffer {
  const buf = Buffer.alloc(GETATTR_OUT_SIZE);
  buf.writeBigUInt64LE(0n, 0);
  buf.writeUInt32LE(0, 8);
  buf.writeUInt32LE(0, 12);
  packFuseAttr(attr, buf, 16);
  return buf;
}

/** struct fuse_open_out: fh u64, open_flags u32, padding u32. */
export const OPEN_OUT_SIZE = 16;

export function packOpenOut(fh: bigint): Buffer {
  const buf = Buffer.alloc(OPEN_OUT_SIZE);
  buf.writeBigUInt64LE(fh, 0);
  buf.writeUInt32LE(0, 8);
  buf.writeUInt32LE(0, 12);
  return buf;
}

/** struct fuse_dirent: ino u64, off u64, namelen u32, type u32, name padded
 *  to 8-byte alignment. Names are NOT NUL-terminated. */
export function packDirent(ino: number, cookie: number, type: number, name: string): Buffer {
  const nameBytes = Buffer.from(name, 'utf8');
  const total = align8(24 + nameBytes.length);
  const buf = Buffer.alloc(total);
  buf.writeBigUInt64LE(BigInt(ino), 0);
  buf.writeBigUInt64LE(BigInt(cookie), 8);
  buf.writeUInt32LE(nameBytes.length, 16);
  buf.writeUInt32LE(type, 20);
  nameBytes.copy(buf, 24);
  return buf;
}

export function align8(n: number): number {
  return (n + 7) & ~7;
}

/** struct fuse_statfs_out payload: five u64s, four named u32s, six spare. */
export const STATFS_OUT_SIZE = 80;

export function packStatfs(files: number): Buffer {
  const buf = Buffer.alloc(STATFS_OUT_SIZE);
  buf.writeBigUInt64LE(BigInt(1_048_576), 0); // blocks
  buf.writeBigUInt64LE(BigInt(1_048_576), 8); // bfree
  buf.writeBigUInt64LE(BigInt(1_048_576), 16); // bavail
  buf.writeBigUInt64LE(BigInt(files), 24);
  buf.writeBigUInt64LE(BigInt(files), 32);
  buf.writeUInt32LE(4096, 40); // bsize
  buf.writeUInt32LE(255, 44); // namelen
  buf.writeUInt32LE(4096, 48); // frsize
  return buf;
}

/** struct fuse_init_out payload — 64 bytes including the spare tail. */
export const INIT_OUT_PAYLOAD_SIZE = 64;

export function packInitOut(kernelMinor: number, kernelFlags: number, maxReadahead: number): Buffer {
  const minor = Math.min(kernelMinor, FUSE_PROTOCOL_MINOR_MAX);
  const flags =
    INIT_FLAGS.ASYNC_READ | INIT_FLAGS.BIG_WRITES |
    INIT_FLAGS.PARALLEL_DIROPS | INIT_FLAGS.MAX_PAGES;
  const buf = Buffer.alloc(INIT_OUT_PAYLOAD_SIZE);
  buf.writeUInt32LE(FUSE_PROTOCOL_MAJOR, 0);
  buf.writeUInt32LE(minor, 4);
  buf.writeUInt32LE(maxReadahead, 8);
  buf.writeUInt32LE(flags, 12);
  buf.writeUInt16LE(0, 16); // max_background
  buf.writeUInt16LE(0, 18); // congestion_threshold
  buf.writeUInt32LE(1024 * 1024, 20); // max_write
  buf.writeUInt32LE(1, 24); // time_gran
  buf.writeUInt16LE(256, 28); // max_pages
  buf.writeUInt16LE(0, 30); // map_alignment
  buf.writeUInt32LE(0, 32); // flags2
  buf.writeUInt32LE(0, 36); // max_stack_depth
  buf.writeUInt16LE(0, 40); // request_timeout
  void kernelFlags;
  return buf;
}

/** fuse_out_header: len u32, error i32, unique u64. */
export function packOutHeader(payloadLength: number, unique: bigint, error = 0): Buffer {
  const header = Buffer.alloc(OUT_HEADER_SIZE);
  header.writeUInt32LE(OUT_HEADER_SIZE + payloadLength, 0);
  header.writeInt32LE(error, 4);
  header.writeBigUInt64LE(unique, 8);
  return header;
}

