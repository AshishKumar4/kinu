// ── statistics ────────────────────────────────────────────────────────────────

export interface LatencySummary {
  readonly n: number;
  readonly minMs: number;
  readonly p50Ms: number;
  readonly p95Ms: number;
  readonly maxMs: number;
  readonly meanMs: number;
}

export const LatencySummarySchema = v.looseObject({
  n: v.number(),
  minMs: v.number(),
  p50Ms: v.number(),
  p95Ms: v.number(),
  maxMs: v.number(),
  meanMs: v.number(),
});

export function summarizeLatencies(samplesMs: readonly number[]): LatencySummary | undefined {
  if (samplesMs.length === 0) return undefined;
  const sorted = [...samplesMs].sort((a, b) => a - b);
  const sum = sorted.reduce((total, value) => total + value, 0);
  const percentile = (p: number): number =>
    sorted[Math.min(sorted.length - 1, Math.ceil(p * sorted.length) - 1)]!;
  return {
    n: sorted.length,
    minMs: sorted[0]!,
    p50Ms: percentile(0.5),
    p95Ms: percentile(0.95),
    maxMs: sorted.at(-1)!,
    meanMs: sum / sorted.length,
  };
}

/**
 * Is bring-up cost dominated by an O(entries) term?
 *
 * Definitional, not a tuned threshold: fit t = a + b·n over the three sample
 * sizes by least squares; call bring-up eager when the fitted per-entry term
 * at the largest tree is more than 3× the intercept — i.e. the linear term
 * dominates whatever fixed cost exists. A lazy daemon (b≈0) never trips this;
 * download-then-index bootstrap does.
 */
export function classifyBootstrap(samples: readonly { entries: number; ms: number }[]): {
  eager: boolean;
  interceptMs: number;
  msPerEntry: number;
  largestEntries: number;
} | undefined {
  if (samples.length < 3) return undefined;
  const n = samples.length;
  const sumX = samples.reduce((t, s) => t + s.entries, 0);
  const sumY = samples.reduce((t, s) => t + s.ms, 0);
  const sumXX = samples.reduce((t, s) => t + s.entries ** 2, 0);
  const sumXY = samples.reduce((t, s) => t + s.entries * s.ms, 0);
  const denominator = n * sumXX - sumX ** 2;
  if (denominator === 0) return undefined;
  const b = (n * sumXY - sumX * sumY) / denominator;
  const a = (sumY - b * sumX) / n;
  const largest = Math.max(...samples.map((s) => s.entries));
  return { eager: Math.abs(b) * largest > 3 * Math.abs(a) && b > 0, interceptMs: a, msPerEntry: b, largestEntries: largest };
}

