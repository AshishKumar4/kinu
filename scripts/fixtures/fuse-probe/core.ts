// ── reference content model ──────────────────────────────────────────────────

/** Deterministic seed for the whole synthetic tree. One seed means one
 *  expected-bytes function, which is what makes every read checkable. */
export const TREE_SEED = 0x5f00d;

/** The range-backed file: 32 MiB served in 128 KiB chunks, generated lazily.
 *  A candidate restore design must answer a slice of such a file without
 *  materializing it; this file is the instrument for that question. */
export const BIG_FILE_BYTES = 32 * 1024 * 1024;
export const CHUNK_BYTES = 128 * 1024;
export const BIG_FILE_CHUNKS = BIG_FILE_BYTES / CHUNK_BYTES;

/** xorshift32 stream, byte-wise little-endian. Pure and cheap: the daemon
 *  regenerates any chunk on demand instead of storing 32 MiB. */
export function canonicalChunk(seed: number, chunkIndex: number): Uint8Array {
  const out = new Uint8Array(CHUNK_BYTES);
  let state = (seed ^ Math.imul(chunkIndex + 1, 0x9e3779b1)) >>> 0;
  if (state === 0) state = 0xa5a5_5aa5;
  for (let offset = 0; offset < CHUNK_BYTES; offset += 4) {
    state ^= state << 13; state >>>= 0;
    state ^= state >>> 17;
    state ^= state << 5; state >>>= 0;
    out[offset] = state & 0xff;
    out[offset + 1] = (state >>> 8) & 0xff;
    out[offset + 2] = (state >>> 16) & 0xff;
    out[offset + 3] = (state >>> 24) & 0xff;
  }
  return out;
}

/** SHA-256 of one canonical chunk, hex. This is the trusted side of the
 *  integrity check: derived from the definition of the bytes, not from an
 *  in-memory copy that could rot the same way. */
export function chunkDigest(seed: number, chunkIndex: number): string {
  return sha256Hex(canonicalChunk(seed, chunkIndex));
}

/** SHA-256 of an arbitrary canonical byte range (chunk-aligned start assumed
 *  not; ranges are checked against regenerated bytes, not chunk digests). */
export function canonicalRange(seed: number, offset: number, length: number): Uint8Array {
  const out = new Uint8Array(length);
  const first = Math.floor(offset / CHUNK_BYTES);
  const last = Math.floor((offset + length - 1) / CHUNK_BYTES);
  let written = 0;
  for (let chunk = first; chunk <= last; chunk++) {
    const bytes = canonicalChunk(seed, chunk);
    const from = Math.max(offset, chunk * CHUNK_BYTES) - chunk * CHUNK_BYTES;
    const to = Math.min(offset + length, (chunk + 1) * CHUNK_BYTES) - chunk * CHUNK_BYTES;
    out.set(bytes.subarray(from, to), written);
    written += to - from;
  }
  return out;
}

export function sha256Hex(bytes: Uint8Array): string {
  const hasher = new Bun.CryptoHasher('sha256');
  hasher.update(bytes);
  return hasher.digest('hex');
}

/** What the serving path must do for every range: regenerate, hash, compare
 *  against the trusted derivation. Returns the reason a read is refused. */
export function verifyChunk(
  seed: number,
  chunkIndex: number,
  actual: Uint8Array,
  corrupt: boolean,
): { ok: true } | { ok: false; reason: string } {
  const expected = chunkDigest(seed, chunkIndex);
  const seen = corrupt ? sha256Hex(xorByte(actual)) : sha256Hex(actual);
  return seen === expected ? { ok: true } : { ok: false, reason: `chunk ${chunkIndex} digest mismatch` };
}

function xorByte(bytes: Uint8Array): Uint8Array {
  const copy = new Uint8Array(bytes.length);
  copy.set(bytes);
  copy[0] ^= 0xff;
  return copy;
}

